package p01_logica;

public class a14_operadores_bitwise {
    public static void main(String[] args) {

        /*
        & - and bit a bit
        | - or bit a bit
        ^ - xor bit a bit
         */

        int n1 = 89;
        int n2 = 60;

        System.out.println(n1 & n2);
        System.out.println(n1 | n2);
        System.out.println(n1 ^ n2);
    }
}
