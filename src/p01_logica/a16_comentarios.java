package p01_logica;

public class a16_comentarios {
    /*
    Este programa é um exemplo para explicar sobre comentários
    esse tipo de comentário é o multi-linha, geralmente utilizado para descrever uma função ou classe
     */
    public static void main(String[] args) {
         int n = 10; //comentário para a variável, neste caso a quantidade de números que serão impressos

        for (int i = 0; i < n ; i++){
            System.out.println(i+1);
        }

        //lembre-se de não encher o código de comentários desnecessários e óbvios
    }
}
