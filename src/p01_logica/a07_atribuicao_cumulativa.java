package p01_logica;

public class a07_atribuicao_cumulativa {
    public static void main(String[] args) {
        int a = 10;
        int b = 5;

        a+=b;

        System.out.println(a);

        /*
        Operadores de atribuição cumulativa

        a+=b    -->    a = a + b
        a-=b    -->    a = a - b
        a*=b    -->    a = a * b
        a/=b    -->    a = a / b
        a%=b    -->    a = a % b
         */



    }
}
